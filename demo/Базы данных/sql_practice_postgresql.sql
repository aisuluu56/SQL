-- 1. Справочники и люди ------------------------------------------------------
CREATE TABLE branches (
    branch_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_name     VARCHAR(100) NOT NULL UNIQUE,
    city            VARCHAR(80) NOT NULL,
    opened_on       DATE NOT NULL
);

CREATE TABLE employees (
    employee_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id       INTEGER NOT NULL REFERENCES branches(branch_id),
    manager_id      INTEGER REFERENCES employees(employee_id),
    first_name      VARCHAR(60) NOT NULL,
    last_name       VARCHAR(60) NOT NULL,
    job_title       VARCHAR(80) NOT NULL,
    salary          NUMERIC(10, 2) NOT NULL CHECK (salary > 0),
    hired_at        DATE NOT NULL,
    email           VARCHAR(120) NOT NULL UNIQUE,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE customers (
    customer_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR(120) NOT NULL,
    email           VARCHAR(120) NOT NULL UNIQUE,
    phone           VARCHAR(25),
    city            VARCHAR(80),
    birth_date      DATE,
    registered_at   DATE NOT NULL,
    loyalty_level   VARCHAR(12) NOT NULL DEFAULT 'bronze'
                    CHECK (loyalty_level IN ('bronze', 'silver', 'gold')),
    referred_by     INTEGER REFERENCES customers(customer_id),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE suppliers (
    supplier_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name   VARCHAR(100) NOT NULL UNIQUE,
    country         VARCHAR(60) NOT NULL,
    contact_email   VARCHAR(120),
    rating          NUMERIC(2, 1) CHECK (rating BETWEEN 1 AND 5)
);

CREATE TABLE categories (
    category_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id       INTEGER REFERENCES categories(category_id),
    category_name   VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE products (
    product_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     INTEGER NOT NULL REFERENCES categories(category_id),
    supplier_id     INTEGER NOT NULL REFERENCES suppliers(supplier_id),
    product_name    VARCHAR(150) NOT NULL,
    sku             VARCHAR(30) NOT NULL UNIQUE,
    list_price      NUMERIC(12, 2) NOT NULL CHECK (list_price > 0),
    cost_price      NUMERIC(12, 2) NOT NULL CHECK (cost_price >= 0),
    created_at      DATE NOT NULL,
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    attributes      JSONB NOT NULL DEFAULT '{}'::jsonb,
    tags            TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    CONSTRAINT chk_product_cost CHECK (cost_price <= list_price)
);

CREATE TABLE stocks (
    branch_id       INTEGER NOT NULL REFERENCES branches(branch_id),
    product_id      INTEGER NOT NULL REFERENCES products(product_id),
    quantity        INTEGER NOT NULL CHECK (quantity >= 0),
    reserved_qty    INTEGER NOT NULL DEFAULT 0 CHECK (reserved_qty >= 0),
    last_restocked  DATE,
    PRIMARY KEY (branch_id, product_id),
    CONSTRAINT chk_reserved_not_above_quantity CHECK (reserved_qty <= quantity)
);

CREATE TABLE coupons (
    coupon_code     VARCHAR(25) PRIMARY KEY,
    discount_type   VARCHAR(10) NOT NULL
                    CHECK (discount_type IN ('fixed', 'percent', 'shipping')),
    discount_value  NUMERIC(10, 2) NOT NULL CHECK (discount_value >= 0),
    valid_from      DATE NOT NULL,
    valid_until     DATE NOT NULL,
    usage_limit     INTEGER CHECK (usage_limit > 0),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_coupon_period CHECK (valid_until >= valid_from)
);

-- 2. Заказы и операции --------------------------------------------------------
CREATE TABLE orders (
    order_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     INTEGER NOT NULL REFERENCES customers(customer_id),
    branch_id       INTEGER NOT NULL REFERENCES branches(branch_id),
    employee_id     INTEGER REFERENCES employees(employee_id),
    coupon_code     VARCHAR(25) REFERENCES coupons(coupon_code),
    order_date      TIMESTAMP NOT NULL,
    status          VARCHAR(12) NOT NULL
                    CHECK (status IN ('new', 'paid', 'shipped', 'completed',
                                     'cancelled', 'returned')),
    delivery_type   VARCHAR(10) NOT NULL
                    CHECK (delivery_type IN ('pickup', 'courier')),
    shipping_city   VARCHAR(80),
    discount_amount NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    delivery_fee    NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
    notes           TEXT
);

CREATE TABLE order_items (
    order_id        INTEGER NOT NULL REFERENCES orders(order_id),
    product_id      INTEGER NOT NULL REFERENCES products(product_id),
    quantity        INTEGER NOT NULL CHECK (quantity > 0),
    unit_price      NUMERIC(12, 2) NOT NULL CHECK (unit_price > 0),
    discount_pct    INTEGER NOT NULL DEFAULT 0 CHECK (discount_pct BETWEEN 0 AND 100),
    PRIMARY KEY (order_id, product_id)
);

CREATE TABLE payments (
    payment_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        INTEGER NOT NULL REFERENCES orders(order_id),
    paid_at         TIMESTAMP NOT NULL,
    amount          NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    method          VARCHAR(16) NOT NULL
                    CHECK (method IN ('card', 'sbp', 'cash', 'bank_transfer')),
    status          VARCHAR(12) NOT NULL
                    CHECK (status IN ('succeeded', 'failed', 'refunded')),
    transaction_ref VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE shipments (
    shipment_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        INTEGER NOT NULL UNIQUE REFERENCES orders(order_id),
    tracking_number VARCHAR(40) NOT NULL UNIQUE,
    carrier         VARCHAR(30) NOT NULL,
    shipped_at      TIMESTAMP NOT NULL,
    delivered_at    TIMESTAMP,
    delivery_status VARCHAR(12) NOT NULL
                    CHECK (delivery_status IN ('in_transit', 'delivered', 'returned')),
    shipping_cost   NUMERIC(10, 2) NOT NULL CHECK (shipping_cost >= 0),
    destination     VARCHAR(160) NOT NULL,
    CONSTRAINT chk_delivery_time CHECK (
        delivered_at IS NULL OR delivered_at >= shipped_at
    )
);

CREATE TABLE returns (
    return_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        INTEGER NOT NULL,
    product_id      INTEGER NOT NULL,
    returned_at     TIMESTAMP NOT NULL,
    quantity        INTEGER NOT NULL CHECK (quantity > 0),
    reason          VARCHAR(30) NOT NULL,
    resolution      VARCHAR(16) NOT NULL
                    CHECK (resolution IN ('refund', 'replacement', 'rejected')),
    CONSTRAINT fk_return_order_line FOREIGN KEY (order_id, product_id)
        REFERENCES order_items(order_id, product_id)
);

CREATE TABLE support_tickets (
    ticket_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     INTEGER NOT NULL REFERENCES customers(customer_id),
    order_id        INTEGER REFERENCES orders(order_id),
    agent_id        INTEGER REFERENCES employees(employee_id),
    created_at      TIMESTAMP NOT NULL,
    closed_at       TIMESTAMP,
    priority        VARCHAR(8) NOT NULL
                    CHECK (priority IN ('low', 'normal', 'high')),
    topic           VARCHAR(35) NOT NULL,
    status          VARCHAR(12) NOT NULL
                    CHECK (status IN ('open', 'in_progress', 'closed')),
    CONSTRAINT chk_ticket_close_date CHECK (
        closed_at IS NULL OR closed_at >= created_at
    )
);

