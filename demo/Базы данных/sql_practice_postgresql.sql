-- По оплаченным/отгруженным/выполненным/возвращённым заказам добавляем
-- платёж на сумму всех позиций с учётом скидок и доставки.
-- Для возвращённых заказов итоговый статус платежа: refunded.
INSERT INTO payments (order_id, paid_at, amount, method, status, transaction_ref)
SELECT o.order_id,
       o.order_date + INTERVAL '25 minutes',
       ROUND(SUM(oi.quantity * oi.unit_price *
                 (100 - oi.discount_pct) / 100.0) - o.discount_amount + o.delivery_fee, 2),
       CASE WHEN o.order_id % 7 = 0 THEN 'cash'
            WHEN o.order_id % 5 = 0 THEN 'bank_transfer'
            WHEN o.order_id % 3 = 0 THEN 'sbp' ELSE 'card' END,
       CASE WHEN o.status = 'returned' THEN 'refunded' ELSE 'succeeded' END,
       'PAY-' || lpad(o.order_id::text, 7, '0')
FROM orders o
JOIN order_items oi ON oi.order_id = o.order_id
WHERE o.status IN ('paid', 'shipped', 'completed', 'returned')
GROUP BY o.order_id, o.order_date, o.status, o.discount_amount, o.delivery_fee;

