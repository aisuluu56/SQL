-- Возвраты: как полностью возвращённые заказы, так и частичные возвраты
-- по выполненным заказам.
INSERT INTO returns (order_id, product_id, returned_at, quantity, reason, resolution)
SELECT o.order_id, oi.product_id,
       o.order_date + (7 + o.order_id % 12) * INTERVAL '1 day',
       1,
       (ARRAY['Не подошёл', 'Брак', 'Не соответствует описанию', 'Повреждение'])[(o.order_id % 4) + 1],
       CASE WHEN o.order_id % 11 = 0 THEN 'rejected'
            WHEN o.order_id % 5 = 0 THEN 'replacement'
            ELSE 'refund' END
FROM orders o
JOIN LATERAL (
    SELECT product_id FROM order_items
    WHERE order_id = o.order_id ORDER BY product_id LIMIT 1
) oi ON TRUE
WHERE o.status = 'returned'
   OR (o.status = 'completed' AND o.order_id % 19 = 0);

INSERT INTO support_tickets (
    customer_id, order_id, agent_id, created_at,
    closed_at, priority, topic, status
)
SELECT COALESCE(o.customer_id, ((g.n * 29) % 320) + 1),
       o.order_id,
       CASE WHEN g.n % 6 = 0 THEN NULL ELSE 7 + (g.n % 30) END,
       COALESCE(o.order_date + (g.n % 10) * INTERVAL '1 day',
           TIMESTAMP '2024-02-01 10:00:00'
           + ((g.n * 37) % 960) * INTERVAL '1 day'),
       CASE WHEN g.n % 4 IN (0, 1) THEN NULL
            ELSE COALESCE(o.order_date + (g.n % 10) * INTERVAL '1 day',
                 TIMESTAMP '2024-02-01 10:00:00'
                 + ((g.n * 37) % 960) * INTERVAL '1 day')
                 + (1 + g.n % 5) * INTERVAL '1 day' END,
       CASE WHEN g.n % 9 = 0 THEN 'high'
            WHEN g.n % 3 = 0 THEN 'low' ELSE 'normal' END,
       (ARRAY['Возврат', 'Оплата', 'Доставка', 'Гарантия', 'Консультация'])[(g.n % 5) + 1],
       CASE WHEN g.n % 4 = 0 THEN 'open'
            WHEN g.n % 4 = 1 THEN 'in_progress' ELSE 'closed' END
FROM generate_series(1, 260) AS g(n)
LEFT JOIN orders o
    ON o.order_id = CASE WHEN g.n % 7 = 0 THEN NULL
                         ELSE ((g.n * 31) % 4800) + 1 END;

